import os
import sqlite3
import time
from contextlib import contextmanager
from datetime import date
from pathlib import Path

from flask import Flask, abort, redirect, render_template, request, url_for
from prometheus_client import Counter, Histogram, generate_latest, CONTENT_TYPE_LATEST

REQUESTS = Counter('stratego_http_requests_total', 'HTTP requests', ['method', 'endpoint', 'status'])
LATENCY = Histogram('stratego_http_request_duration_seconds', 'HTTP request duration', ['endpoint'])


def create_app(config=None):
    app = Flask(__name__)
    app.config.update(DATABASE=os.environ.get('DATABASE_PATH', 'data/stratego.db'), DATABASE_URL=os.environ.get('DATABASE_URL'))
    if config:
        app.config.update(config)
    postgres = bool(app.config['DATABASE_URL'])
    if not postgres:
        Path(app.config['DATABASE']).parent.mkdir(parents=True, exist_ok=True)

    @contextmanager
    def db():
        if postgres:
            import psycopg
            from psycopg.rows import dict_row
            connection = psycopg.connect(app.config['DATABASE_URL'], row_factory=dict_row)
        else:
            connection = sqlite3.connect(app.config['DATABASE'], timeout=10)
            connection.row_factory = sqlite3.Row
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def execute(connection, query, values=()):
        return connection.execute(query.replace('?', '%s') if postgres else query, values)

    with db() as connection:
        if postgres:
            # Serialize schema initialization when multiple replicas start together.
            connection.execute('SELECT pg_advisory_xact_lock(731642189)')
        primary_key = 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY'
        connection.execute(f"CREATE TABLE IF NOT EXISTS tasks (id {primary_key}, title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', due_date TEXT, status TEXT NOT NULL DEFAULT 'todo', priority TEXT NOT NULL DEFAULT 'medium')")
        if postgres:
            connection.execute("ALTER TABLE tasks ADD COLUMN IF NOT EXISTS priority TEXT NOT NULL DEFAULT 'medium'")
        elif 'priority' not in [row['name'] for row in connection.execute('PRAGMA table_info(tasks)')]:
            connection.execute("ALTER TABLE tasks ADD COLUMN priority TEXT NOT NULL DEFAULT 'medium'")

    @app.before_request
    def start_timer():
        request.start_time = time.monotonic()

    @app.after_request
    def record_metrics(response):
        if request.endpoint != 'metrics':
            endpoint = request.endpoint or 'unknown'
            REQUESTS.labels(request.method, endpoint, response.status_code).inc()
            LATENCY.labels(endpoint).observe(time.monotonic() - request.start_time)
        return response

    @app.get('/')
    def index():
        status = request.args.get('status', 'all')
        sorting = request.args.get('sort', 'urgency')
        if status not in ('all', 'todo', 'doing', 'done') or sorting not in ('urgency', 'newest'):
            abort(400)
        order = "due_date IS NULL, due_date, CASE priority WHEN 'high' THEN 0 WHEN 'medium' THEN 1 ELSE 2 END, id DESC" if sorting == 'urgency' else 'id DESC'
        with db() as connection:
            tasks = execute(connection, 'SELECT * FROM tasks' + (' WHERE status = ?' if status != 'all' else " WHERE status != 'done'") + ' ORDER BY ' + order, (status,) if status != 'all' else ()).fetchall()
        today = date.today()
        def reminder(task):
            if not task['due_date'] or task['status'] == 'done':
                return ''
            days = (date.fromisoformat(task['due_date']) - today).days
            return 'Overdue' if days < 0 else 'Due today' if days == 0 else 'Due soon' if days <= 3 else 'Upcoming'
        return render_template('index.html', tasks=tasks, status=status, sorting=sorting, reminder=reminder)

    def validate():
        title = request.form.get('title', '').strip()
        description = request.form.get('description', '').strip()
        due = request.form.get('due_date', '').strip() or None
        status = request.form.get('status', 'todo')
        priority = request.form.get('priority', '')
        if not title or len(title) > 200 or len(description) > 2000 or status not in ('todo', 'doing', 'done') or priority not in ('low', 'medium', 'high'):
            abort(400)
        if due:
            try:
                parsed = date.fromisoformat(due)
                if parsed.isoformat() != due:
                    abort(400)
            except ValueError:
                abort(400)
        return title, description, due, status, priority

    @app.post('/tasks')
    def create_task():
        with db() as connection:
            execute(connection, 'INSERT INTO tasks(title, description, due_date, status, priority) VALUES(?,?,?,?,?)', validate())
        return redirect(url_for('index'))

    @app.post('/tasks/<int:task_id>/edit')
    def edit_task(task_id):
        values = validate()
        with db() as connection:
            cursor = execute(connection, 'UPDATE tasks SET title=?, description=?, due_date=?, status=?, priority=? WHERE id=?', (*values, task_id))
            if not cursor.rowcount:
                abort(404)
        return redirect(url_for('index'))

    @app.post('/tasks/<int:task_id>/delete')
    def delete_task(task_id):
        with db() as connection:
            cursor = execute(connection, 'DELETE FROM tasks WHERE id=?', (task_id,))
            if not cursor.rowcount:
                abort(404)
        return redirect(url_for('index'))

    @app.get('/healthz')
    def health():
        with db() as connection:
            connection.execute('SELECT 1')
        return {'status': 'ok'}

    @app.get('/metrics')
    def metrics():
        return generate_latest(), 200, {'Content-Type': CONTENT_TYPE_LATEST}

    return app
